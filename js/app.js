function schemeFeature(name) {
  return '<div class="scheme-feature">' +
    '<div class="scheme-feature-name">' + esc(name) + "</div>" +
    '<div class="scheme-mini scheme-mini-auditor">🔍 Аудитор</div>' +
    '<div class="scheme-mini-arrow">↓</div>' +
    '<div class="scheme-mini scheme-mini-impl">🔨 Исполнитель</div>' +
    '<div class="scheme-mini-arrow">↓</div>' +
    '<div class="scheme-mini scheme-mini-reviewer">🔍 Reviewer</div>' +
    "</div>";
}

function schemeHtml() {
  return '<div class="scheme">' +
    '<div class="scheme-node scheme-user">👤 Пользователь<span class="scheme-say">«Хочу реализовать X»</span></div>' +
    '<div class="scheme-arrow">↓</div>' +
    '<div class="scheme-node scheme-brain">🧠 Оркестратор</div>' +
    '<div class="scheme-arrow">↓</div>' +
    '<div class="scheme-split">' +
      '<div class="scheme-branch"><div class="scheme-node scheme-plan">📋 План</div></div>' +
      '<div class="scheme-branch">' +
        '<div class="scheme-node scheme-audit">🔍 Аудит</div>' +
        '<div class="scheme-tags"><span>Костыли · Архитектура</span><span>Overengineering · Reference</span></div>' +
      "</div>" +
    "</div>" +
    '<div class="scheme-arrow">↓</div>' +
    '<div class="scheme-node scheme-user">👤 Подтверждение</div>' +
    '<div class="scheme-arrow">↓</div>' +
    '<div class="scheme-node scheme-brain">🚦 Оркестратор</div>' +
    '<div class="scheme-arrow">↓&nbsp;&nbsp;&nbsp;↓&nbsp;&nbsp;&nbsp;↓ <span class="scheme-arrow-label">параллельно</span></div>' +
    '<div class="scheme-features">' +
      schemeFeature("Фича 1") + schemeFeature("Фича 2") + schemeFeature("Фича 3") +
    "</div>" +
    '<div class="scheme-arrow">↓</div>' +
    '<div class="scheme-node scheme-brain">🧠 Оркестратор</div>' +
    '<div class="scheme-arrow">↓</div>' +
    '<div class="scheme-node scheme-final">👤 Студент<span class="scheme-say">готовый результат</span></div>' +
    "</div>";
}

function renderScheme() {
  var box = document.getElementById("scheme");
  if (!box) return;
  var html = '<div class="scheme-card animate-fade-up">';
  html += '<div class="scheme-head"><div class="scheme-icon">🧭</div><div>';
  html += "<h2>Схема методологии</h2>";
  html += '<p>Один запрос пользователя превращается в работу команды агентов: оркестратор планирует и проводит аудит, вы подтверждаете, а фоновые агенты ведут каждую фичу через цепочку Аудитор → Исполнитель → Reviewer.</p>';
  html += "</div></div>";
  html += schemeHtml();
  html += "</div>";
  box.innerHTML = html;
}

