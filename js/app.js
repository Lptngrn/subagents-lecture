function pad(n) { return String(n).padStart(2, "0"); }
function stepsWord(n) {
  var m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return "блок";
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return "блока";
  return "блоков";
}

